const Presets = {
  /** All available preset scenes. */
  list: PRESETS,

  /**
   * Draw `preset` centered on the grid, scaled (nearest neighbor) to fit
   * within CONFIG.PRESETS.MAX_FRACTION of the grid in each dimension.
   * Does not clear the grid; empty ('.') cells are left untouched.
   * Returns the scale factor used.
   */
  apply(grid, preset) {
    const art = preset.art;

    // Trim the empty border so scaling and centering are based on the
    // visible content, not the art's padding.
    let minX = Infinity, minY = Infinity, maxX = -1, maxY = -1;
    for (let y = 0; y < art.length; y++) {
      for (let x = 0; x < art[y].length; x++) {
        if (art[y][x] === '.') continue;
        minX = Math.min(minX, x);
        minY = Math.min(minY, y);
        maxX = Math.max(maxX, x);
        maxY = Math.max(maxY, y);
      }
    }
    const artW = maxX - minX + 1;
    const artH = maxY - minY + 1;

    const maxW = Math.floor(grid.width * CONFIG.PRESETS.MAX_FRACTION);
    const maxH = Math.floor(grid.height * CONFIG.PRESETS.MAX_FRACTION);
    const scale = Math.max(1, Math.min(Math.floor(maxW / artW), Math.floor(maxH / artH)));

    const offsetX = Math.floor((grid.width - artW * scale) / 2);
    const offsetY = Math.floor((grid.height - artH * scale) / 2);

    for (let y = minY; y <= maxY; y++) {
      for (let x = minX; x <= maxX; x++) {
        const material = PRESET_GLYPHS[art[y][x]] ?? MATERIALS.EMPTY;
        if (material === MATERIALS.EMPTY) continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            grid.set(offsetX + (x - minX) * scale + sx, offsetY + (y - minY) * scale + sy, material);
          }
        }
      }
    }
    return scale;
  },

  /**
   * Clear the grid, apply a random preset to it, and return the chosen
   * preset. Used on load and by the Clear button.
   */
  random(grid) {
    grid.clear();
    const preset = PRESETS[(Math.random() * PRESETS.length) | 0];
    this.apply(grid, preset);
    return preset;
  },
};
